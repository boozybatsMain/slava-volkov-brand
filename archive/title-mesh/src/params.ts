import type { ResolvedConfig } from '../../../core/types'

/**
 * ─────────────────────────────────────────────────────────────────────────────
 *  3D-ТАЙТЛ, РЕЖИМ «mesh» — ТОНКАЯ НАСТРОЙКА
 * ─────────────────────────────────────────────────────────────────────────────
 *  Композиция (позиция / ширина / поворот / наклон / перспектива / размер
 *  пикселя / реакция на мышь) задаётся в hero.config.ts → title.
 *  Здесь — только «характер» самого объекта: геометрия букв, материал,
 *  дешёвый рендер. Единица длины для геометрии — высота заглавной буквы (1 = cap height).
 *  Живая подстройка: ?title=mesh&meshtune
 * ─────────────────────────────────────────────────────────────────────────────
 */
export const meshTitleParams = {
  // ── Геометрия букв ──────────────────────────────────────────────────────────
  geometry: {
    /** Глубина экструзии (доли высоты буквы). 0.25 — тонкая плашка, 0.6 — брусок. */
    depth: 0.55,
    /** Первая (внешняя) фаска: ширина = глубина, доли высоты буквы. 0 = без фаски. 0..0.06 */
    bevelOuter: 0.032,
    /** Плоская ступенька между фасками (глубина). Даёт «двойную» линию на ребре. 0..0.05 */
    bevelStep: 0.02,
    /** Вторая фаска (ближе к боковине). 0..0.06 */
    bevelInner: 0.03,
    /** Шов посередине боковины: глубина канавки. 0 = без шва. 0..0.02 */
    seam: 0.008,
    /** Где проходит шов по глубине (0 = у лица, 1 = у задней стенки). */
    seamAt: 0.5,
    /** Сколько отрезков на каждую кривую шрифта. 1–2 = грубые грани, как в старом CGI; 8 = гладко. */
    curveSegments: 2,
    /** Порог сглаживания нормалей на углах контура, градусы. Меньше — больше рубленых граней. */
    crease: 38,
    /** Горизонтальное сжатие букв (1 = как в шрифте). 0.8..1.1 */
    condense: 1.03,
    /** Трекинг: доп. расстояние между буквами (доли высоты буквы). Отрицательное — плотнее. */
    tracking: 0,
    /**
     * Изгиб строки вокруг вертикальной оси, градусы на всю длину надписи.
     * > 0 — дальний конец (VOLKOV) заворачивает от зрителя, < 0 — к зрителю.
     * 0 = плоская строка. -20..30
     */
    bend: -7.5,
    /** Пробел между SLAVA и VOLKOV (доли высоты буквы). */
    wordSpace: 0.71,
  },

  // ── Базовая поза (как объект «снят» в референсе) ────────────────────────────
  pose: {
    /** Разворот вокруг вертикали, градусы: + = правый конец уходит вдаль. */
    yaw: 46.5,
    /** Наклон вокруг горизонтали, градусы: − = верх завален назад (видны нижние грани). */
    pitch: -6.5,
    /** Наклон в плоскости букв, градусы (+ = против часовой). */
    roll: -1.3,
    /**
     * Дистанция камеры в высотах буквы при title.perspective = 1.
     * Меньше = сильнее перспектива (SLAVA крупнее VOLKOV). 4..12
     */
    distance: 11.3,
    /**
     * Смещение объекта от оси «объектива» (доли дистанции, ≈ тангенс угла).
     * shiftX > 0 — камера левее надписи (видны левые боковины букв),
     * shiftY > 0 — камера ниже (видны нижние грани). -1..1
     */
    shiftX: 0.13,
    shiftY: 0.08,
    /**
     * Точка, вокруг которой надпись поворачивается к курсору:
     * 0 = левый край S, 0.5 = середина надписи, 1 = конец VOLKOV.
     */
    pivot: 0.3,
  },

  // ── Материал: матовый псевдохром ────────────────────────────────────────────
  material: {
    /** Базовый цвет лицевых граней (серебро) — проступает там, где отражение слабое. */
    face: '#b3b3b5',
    /** Цвет боковин (тёмный серый металл). */
    side: '#8a8b8f',
    /** Голубой оттенок «неба» в отражении. */
    sky: '#93aef5',
    /** Цвет бело-голубых бликов. */
    glint: '#eef3ff',
    /** Цвет «земли» в отражении (тёмные участки граней). */
    ground: '#6f6f72',
    /**
     * Высота горизонта в отражении, градусы. Больше — лица букв темнее и «серее»
     * (видят землю), меньше — светлее и голубее (видят небо). 0..20
     */
    horizon: 6,
    /**
     * «Подушка»: насколько нормали лица буквы наклоняются от центра к краям.
     * Даёт в каждой букве переход небо → горизонт → земля сверху вниз. 0..1
     */
    bulge: 0.25,
    /**
     * «Фотошопная» подсветка фасок: светлые верх/лево, тёмные низ/право —
     * даёт чёткую рамку вокруг лица буквы. 0 = только отражение, 1 = только свет.
     */
    bevelLight: 0.6,
    /** Контраст материала вокруг среднего серого (1 = как есть). 0.8..1.5 */
    contrast: 1.15,
    /** Сила отражения на лицевых гранях. 0..1 */
    reflect: 0.75,
    /** Сила отражения на боковинах. 0..1 */
    sideReflect: 0.35,
    /** Матовость: 0 = зеркальный хром, 1 = почти пластик. */
    matte: 0.3,
    /** Пятнистость сине-белых бликов. 0..1.5 */
    blotch: 0.9,
    /** Неровность поверхности (кривые отражения на плоских гранях). 0..1 */
    warp: 0.5,
    /** Яркость двух «студийных ламп» в отражении — сине-белые пятна на SLAVA. 0..2 */
    lamp: 1,
    /** Острые точечные блики (две лампы, Блинн-Фонг) — «странные» сине-белые искры. 0..2 */
    specular: 1,
    /** Насколько далеко отражение «едет» за мышью (при title.response.highlight = 1), радианы. */
    envShift: 0.45,
  },

  // ── Дешёвый рендер ─────────────────────────────────────────────────────────
  render: {
    /** Бит на канал цвета (5 = 15-битный «High Color» конца 90-х). 4..8 */
    colorBits: 5,
    /** Упорядоченный дизеринг Байера при понижении цветности. 0..1 */
    dither: 1,
    /** Белёсая бахрома по краю, будто вырезали с белого фона. 0..1 */
    fringe: 0.55,
    /** Амплитуда субпиксельного дрожания камеры в движении (в пикселях рендера). 0..1.5 */
    jitter: 0.7,
    /** Как часто в движении проскакивают сдвиги строк / столбцов на 1 px. 0..2 */
    glitch: 1,
    /** Мерцание края (порог альфы) в движении. 0..1 */
    edgeFlicker: 0.5,
    /** Частота «дешёвого» обновления шума, Гц. 12–30. */
    tickRate: 20,
  },
}

export type MeshTitleParams = typeof meshTitleParams

/**
 * Единственная точка чтения параметров. Чтобы перенести их в hero.config.ts,
 * достаточно заменить тело на `return config.title.mesh`.
 */
export function getMeshTitleParams(_config: ResolvedConfig): MeshTitleParams {
  return meshTitleParams
}
